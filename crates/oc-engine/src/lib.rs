//! OpenCAD's engine without a shell (OVERHAUL_PLAN W1b): what was `oc-app`'s engine thread.
//!
//! - [`engine`]: the jobs the webview's commands become (`engine_*`, `asm_*`), served one at a
//!   time on one thread that owns the OCCT kernel and the regenerator; display meshes go to
//!   the renderer through the [`engine::MeshStore`].
//! - [`asm`]: assemblies (open, build, drag, evaluate, save).
//! - [`pack`]: the binary reply layout (`OCR1`); [`bodymesh`]: a body as the webview's `BodyMesh`.
//! - [`request`]: a command by name with the webview's arguments, as one entry (the browser's
//!   engine worker, `oc-web`).
//! - [`hosts`]: parts regenerated by workers the engine cannot wait for (the browser's host
//!   workers): a request that needs them is deferred, then run again with their results.
//!
//! The desktop app (`oc-app`) runs it on a thread behind Tauri's commands; the browser runs
//! it in a Web Worker (`oc-web`, `src/web/`).
pub mod asm;
pub mod bodymesh;
pub mod engine;
pub mod hosts;
pub mod pack;
pub mod request;
