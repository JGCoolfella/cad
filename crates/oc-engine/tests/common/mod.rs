//! Shared by the engine's tests: engines, requests, packed replies, the corpus.
#![allow(dead_code)]
use std::path::{Path, PathBuf};
use std::sync::Arc;

use oc_asm::Assembler;
use oc_engine::engine::{Engine, MeshStore};
use oc_engine::hosts::Prepared;
use oc_engine::request::{request, Answer};
use oc_kernel_occt::OcctKernel;
use serde_json::{json, Value};

pub fn corpus() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../corpus")
}

/// An engine regenerating every part itself, one by one.
pub fn engine() -> Engine {
    let mut a = Assembler::new(OcctKernel::default());
    a.workers = 1;
    Engine::new(a, Arc::new(MeshStore::default()), None)
}

/// An engine whose parts are regenerated by "host workers" (`Prepared`), and its handle.
pub fn hosted(width: usize) -> (Engine, Prepared) {
    let p = Prepared::new(width);
    let mut a = Assembler::new(OcctKernel::default());
    a.runner = Some(Box::new(p.clone()));
    (Engine::new(a, Arc::new(MeshStore::default()), Some(p.stats())), p)
}

pub fn json(e: &mut Engine, cmd: &str, args: Value) -> Value {
    match request(e, cmd, args) {
        Ok(Answer::Json(v)) => v,
        r => panic!("{cmd}: {r:?}"),
    }
}

pub fn bytes(e: &mut Engine, cmd: &str, args: Value) -> Vec<u8> {
    match request(e, cmd, args) {
        Ok(Answer::Bytes(b)) => b,
        r => panic!("{cmd}: {:?}", r.map(|a| matches!(a, Answer::Deferred))),
    }
}

/// A packed reply's header (`oc_engine::pack`).
pub fn header(b: &[u8]) -> Value {
    assert_eq!(&b[..4], b"OCR1");
    let n = u32::from_le_bytes(b[4..8].try_into().unwrap()) as usize;
    serde_json::from_slice(&b[8..8 + n]).unwrap()
}

/// A packed reply's array section.
pub fn arrays(b: &[u8]) -> &[u8] {
    let n = u32::from_le_bytes(b[4..8].try_into().unwrap()) as usize;
    &b[8 + n..]
}

/// The corpus parts: name, document (its JSON), oracle.
pub fn parts() -> Vec<(String, Value, Value)> {
    let mut out = vec![];
    for e in std::fs::read_dir(corpus()).unwrap() {
        let p = e.unwrap().path();
        if p.extension().is_some_and(|x| x == "ocpart") {
            let name = p.file_stem().unwrap().to_string_lossy().to_string();
            let doc: Value = serde_json::from_str(&std::fs::read_to_string(&p).unwrap()).unwrap();
            let oracle: Value = serde_json::from_str(&std::fs::read_to_string(p.with_extension("json")).unwrap()).unwrap();
            out.push((name, doc, oracle));
        }
    }
    out.sort_by(|a, b| a.0.cmp(&b.0));
    out
}

/// The final body the oracle expects, corrected as `oc-app`'s `smoke::check_corpus` corrects
/// it (section 8, E5: `through-mid-dir2`), and the slack its rounding allows per value.
pub fn expected(name: &str, oracle: &Value) -> Value {
    let last = oracle["steps"].as_array().unwrap().iter().rev().find(|s| s.get("body").is_some()).unwrap();
    let mut b = last["body"].clone();
    let round = |x: f64| 0.5 * 10f64.powi(x.abs().log10().floor() as i32 - 5) * (1.0 + 1e-9);
    b["slack"] = json!({ "volume": round(b["volume"].as_f64().unwrap()), "area": round(b["area"].as_f64().unwrap()) });
    if name == "through-mid-dir2" {
        let sub = |b: &mut Value, k: &str, x: f64| b[k] = json!(b[k].as_f64().unwrap() - x);
        sub(&mut b, "volume", 100.0 * 114.288);
        sub(&mut b, "area", 4.0 * 10.0 * 114.288);
        b["faces"] = json!(b["faces"].as_u64().unwrap() - 5);
        b["edges"] = json!(b["edges"].as_u64().unwrap() - 12);
        b["slack"]["volume"] = json!(b["slack"]["volume"].as_f64().unwrap() + 100.0 * 0.0005);
        b["slack"]["area"] = json!(b["slack"]["area"].as_f64().unwrap() + 40.0 * 0.0005);
    }
    b
}
