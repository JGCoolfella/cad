/// <reference lib="webworker" />
/**
 * The engine worker (OVERHAUL_PLAN W1b): the browser's engine thread. It loads the engine
 * program (`crates/oc-web`) and answers the page's `invoke` commands one at a time, with the
 * desktop app's replies (`oc_engine::request`).
 *
 * Several parts at once regenerate on geometry host workers ([`HostPool`]). The engine
 * program cannot wait for them inside a request (one thread, no shared memory), so a request
 * that needs them is deferred (`oc_engine::hosts`): this worker gets the wanted part jobs,
 * has the host workers regenerate them, hands the results over and runs the request again,
 * which then answers exactly as natively.
 */
import { DEFERRED, BYTES_REPLY, JSON_REPLY, load, own, type OcWeb } from "./module";
import { HostPool } from "./hosts";
import type { EngineIn, EngineOut, RequestStats } from "./protocol";

const scope = self as unknown as DedicatedWorkerGlobalScope;
const post = (m: EngineOut, transfer: Transferable[] = []) => scope.postMessage(m, transfer);

/** Deferrals of one request before its parts are left to the engine (never reached so far). */
const MAX_ROUNDS = 8;

let mod: OcWeb | null = null;
let pool: HostPool | null = null;
/** Requests run one at a time, in arrival order. */
let queue: Promise<unknown> = Promise.resolve();

async function start(m: Extract<EngineIn, { type: "start" }>) {
  const t0 = performance.now();
  mod = await load(m.moduleUrl);
  mod.startEngine(m.hosts, m.budgetMb);
  if (m.hosts > 0) pool = new HostPool({ moduleUrl: m.moduleUrl, size: m.hosts, faults: m.faults, timeoutMs: m.hostTimeoutMs, started: () => mod?.hostsStarted() });
  post({ type: "ready", identity: mod.identity(), startMs: performance.now() - t0 });
}

/** Runs one command to its end, regenerating deferred parts on the host workers. */
async function serve(cmd: string, args: unknown): Promise<{ kind: number; bytes: Uint8Array; stats: RequestStats }> {
  const m = mod!;
  const stats: RequestStats = { deferrals: 0, hostParts: 0, engineMs: 0, hostsMs: 0 };
  let alone = false;
  for (;;) {
    const t0 = performance.now();
    if (alone) m.setDefer(false);
    const r = m.request(cmd, args);
    if (alone) m.setDefer(true);
    stats.engineMs += performance.now() - t0;
    if (r.kind !== DEFERRED) {
      if (m.takeWarm()) pool?.warm();
      return { ...r, stats };
    }
    stats.deferrals++;
    const jobs = m.wanted();
    if (!pool || stats.deferrals > MAX_ROUNDS) {
      alone = true;
      continue;
    }
    const t1 = performance.now();
    const results = await pool.run(jobs);
    stats.hostsMs += performance.now() - t1;
    results.forEach((r, i) => {
      if (!r) return;
      stats.hostParts++;
      m.prepare(i, r.kind, r.payload);
    });
    // A part no host worker could take is regenerated by the engine (as natively).
    alone = results.some((r, i) => !r && jobs[i].length > 0);
  }
}

async function invoke(id: number, cmd: string, args: unknown) {
  try {
    const r = await serve(cmd, args);
    const buf = own(r.bytes);
    if (r.kind === JSON_REPLY) post({ type: "reply", id, ok: true, json: buf, stats: r.stats }, [buf]);
    else if (r.kind === BYTES_REPLY) post({ type: "reply", id, ok: true, bytes: buf, stats: r.stats }, [buf]);
    else post({ type: "reply", id, ok: false, error: new TextDecoder().decode(r.bytes) });
  } catch (e) {
    if (!stopped(e)) {
      post({ type: "reply", id, ok: false, error: String((e as Error)?.message ?? e) });
      return;
    }
    // The engine program trapped, aborted or exited: what it held is gone.
    post({ type: "reply", id, ok: false, error: `the engine stopped: ${String((e as Error)?.message ?? e)}` });
    post({ type: "fatal", error: String((e as Error)?.stack ?? e) });
    pool?.stop();
    scope.close();
  }
}

/** Whether an exception means the engine program can no longer be used: a WebAssembly trap
 * (Emscripten's abort is one too) or Emscripten's exit. A JavaScript error of this worker's
 * own (a reply it could not hand over) leaves the program as it was. */
function stopped(e: unknown) {
  return e instanceof WebAssembly.RuntimeError || (e as { name?: string })?.name === "ExitStatus" || !mod;
}

function fs(m: Extract<EngineIn, { type: "fs" }>) {
  const FS = mod!.m.FS;
  try {
    let json: unknown = null;
    if (m.op === "write") {
      const dir = m.path.replace(/\/[^/]*$/, "");
      if (dir) FS.mkdirTree(dir);
      FS.writeFile(m.path, new Uint8Array(m.data!));
    } else if (m.op === "mkdir") FS.mkdirTree(m.path);
    else if (m.op === "list") json = FS.readdir(m.path).filter((n) => n !== "." && n !== "..");
    else {
      const b = own(FS.readFile(m.path));
      post({ type: "reply", id: m.id, ok: true, bytes: b }, [b]);
      return;
    }
    const buf = own(new TextEncoder().encode(JSON.stringify(json)));
    post({ type: "reply", id: m.id, ok: true, json: buf }, [buf]);
  } catch (e) {
    post({ type: "reply", id: m.id, ok: false, error: `${m.path}: ${String((e as Error)?.message ?? e)}` });
  }
}

scope.onmessage = (ev: MessageEvent<EngineIn>) => {
  const m = ev.data;
  if (m.type === "start") queue = queue.then(() => start(m)).catch((e) => post({ type: "fatal", error: `the engine did not start: ${String((e as Error)?.message ?? e)}` }));
  else if (m.type === "invoke") queue = queue.then(() => invoke(m.id, m.cmd, m.args));
  else if (m.type === "fs") queue = queue.then(() => fs(m));
};
